#!/usr/bin/env python3
"""Extracts per-surface design tokens from the original CSS/Tailwind/inline styles and diffs them
against the OS CSS. Writes docs/parity/design-tokens.md and design-diff.md. Offline only."""
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
LEGACY = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / ".runtime/legacy-source"
L = LEGACY / "frontend"
OS = REPO / "frontend/src"

ORIGINAL = {
    "public": ["src/club-site/public.css", "src/club-site/HomepageRefinements.css", "src/club-site/SidelineBanner.css", "src/index.css",
               "src/App.css", "tailwind.config.js", "src/club-site/*.jsx", "src/pages/*.jsx"],
    "admin": ["src/index.css", "tailwind.config.js", "src/pages/AdminPanel.jsx", "src/pages/admin/*.jsx"],
    "mobile": ["src/mobile/mobile-theme.css", "src/mobile/mobile-typography.css", "src/mobile/mobile-ui.css", "src/mobile/mockup-role-ui.css",
               "src/mobile/pages/*.jsx", "src/mobile/components/*.jsx"],
    "pos": ["src/pos/pos.css", "src/pos/PosApp.jsx"],
}
CURRENT = {
    "public": ["lib/public/public.css", "routes/app.css", "lib/accessibility.css", "lib/public/**/*.svelte", "routes/+layout.svelte",
               "routes/+page.svelte", "routes/[a-z]*/**/*.svelte"],
    "admin": ["lib/admin/admin.css", "lib/admin/**/*.svelte", "routes/admin/**/*.svelte"],
    "mobile": ["lib/mobile/components/mobile-theme.css", "lib/mobile/**/*.svelte", "routes/app/**/*.svelte"],
    "pos": ["routes/admin/pos/**/*.svelte"],
}
CATEGORIES = {
    "custom properties": re.compile(r"(--[a-zA-Z0-9-]+)\s*:\s*([^;}\n]+)"),
    "font families": re.compile(r"font-family\s*:\s*([^;}\n]+)|fontFamily:\s*\{([^}]*)\}|font-\['([^']+)'\]"),
    "font sizes": re.compile(r"font-size\s*:\s*([^;}\n]+)|\btext-\[(\d+(?:\.\d+)?(?:px|rem))\]|fontSize:\s*['\"]?([\d.]+(?:px|rem)?)"),
    "font weights": re.compile(r"font-weight\s*:\s*([^;}\n]+)|\bfont-(thin|light|normal|medium|semibold|bold|extrabold|black)\b"),
    "line heights": re.compile(r"line-height\s*:\s*([^;}\n]+)|\bleading-\[([^\]]+)\]"),
    "letter spacing": re.compile(r"letter-spacing\s*:\s*([^;}\n]+)|\btracking-\[([^\]]+)\]"),
    "max widths": re.compile(r"max-width\s*:\s*([^;}\n]+)|\bmax-w-\[([^\]]+)\]|\bmax-w-(\d?xl|screen-\w+|\d+)\b"),
    "radii": re.compile(r"border-radius\s*:\s*([^;}\n]+)|\brounded-\[([^\]]+)\]"),
    "breakpoints": re.compile(r"@media\s*([^{]+)\{"),
    "colours": re.compile(r"(#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\))"),
}


def files(base, patterns):
    seen = []
    for pattern in patterns:
        for f in sorted(base.glob(pattern)):
            if f.is_file() and ".test." not in f.name and f not in seen:
                seen.append(f)
    return seen


def extract(base, patterns, root):
    tokens = defaultdict(lambda: defaultdict(list))  # category -> value -> [file:line]
    for f in files(base, patterns):
        rel = f.relative_to(root)
        for lineno, line in enumerate(f.read_text(errors="ignore").splitlines(), 1):
            for cat, rx in CATEGORIES.items():
                for m in rx.finditer(line):
                    if cat == "custom properties":
                        value = f"{m.group(1)}: {m.group(2).strip()}"
                    else:
                        value = next((g for g in m.groups() if g), "").strip().rstrip("!important").strip()
                    if value and len(value) < 140:
                        tokens[cat][value].append(f"{rel}:{lineno}")
    return tokens


def cite(refs):
    return f"`{refs[0]}`" + (f" (+{len(refs) - 1})" if len(refs) > 1 else "")


def main():
    out = REPO / "docs/parity"
    out.mkdir(parents=True, exist_ok=True)
    orig = {s: extract(L, p, LEGACY) for s, p in ORIGINAL.items()}
    cur = {s: extract(OS, p, REPO) for s, p in CURRENT.items()}
    md = ["# Original design tokens per surface", "",
          "Generated by `scripts/parity/design_tokens.py` from the read-only original source. Each value cites its first source line "
          "(`frontend/...:line`, relative to the original repository) and the number of further occurrences.", "",
          "## Key layout tokens (public)", ""]
    key = [("rail width", r"--public-rail:\s*116px"), ("header height", r"--public-header:\s*76px"), ("black", r"--public-black:\s*#080808"),
           ("gold", r"--public-gold:\s*#f5a623")]
    for label, rx in key:
        hits = [(v, r) for v, r in orig["public"]["custom properties"].items() if re.search(rx, v)]
        md.append(f"- **{label}**: " + ("; ".join(f"`{v}` {cite(r)}" for v, r in hits) if hits else "not found"))
    for surface in ORIGINAL:
        md += ["", f"## {surface.capitalize()}", "", "Sources: " + ", ".join(f"`frontend/{p}`" for p in ORIGINAL[surface]), ""]
        for cat in CATEGORIES:
            values = orig[surface][cat]
            if not values:
                continue
            ranked = sorted(values.items(), key=lambda kv: (-len(kv[1]), kv[0]))
            limit = 400 if cat in ("custom properties", "font families", "breakpoints", "max widths") else 120
            md += [f"### {cat} ({len(values)} distinct)", "", "| Value | Uses | Source |", "|---|---|---|"]
            md += [f"| `{v.replace('|', '/')}` | {len(r)} | {cite(r)} |" for v, r in ranked[:limit]]
            md.append("")
    (out / "design-tokens.md").write_text("\n".join(md) + "\n")

    diff = ["# Design diff: original vs current OS CSS", "",
            "Generated by `scripts/parity/design_tokens.py`. *Only in original* values are candidates to add or match in the OS; "
            "*only in OS* values are candidates to remove or replace. Same-name custom properties with different values are listed first.", ""]
    totals = []
    for surface in ORIGINAL:
        o, c = orig[surface], cur[surface]
        diff += [f"## {surface.capitalize()}", ""]
        oprops = {v.split(":", 1)[0]: (v.split(":", 1)[1].strip(), r) for v, r in o["custom properties"].items()}
        cprops = {v.split(":", 1)[0]: (v.split(":", 1)[1].strip(), r) for v, r in c["custom properties"].items()}
        changed = [(k, oprops[k], cprops[k]) for k in sorted(oprops.keys() & cprops.keys()) if oprops[k][0] != cprops[k][0]]
        diff += [f"### Same custom property, different value ({len(changed)})", "", "| Property | Original | OS |", "|---|---|---|"]
        diff += [f"| `{k}` | `{a[0]}` {cite(a[1])} | `{b[0]}` {cite(b[1])} |" for k, a, b in changed] + [""]
        missing_props = sorted(oprops.keys() - cprops.keys())
        diff += [f"### Custom properties only in original ({len(missing_props)})", "", ", ".join(f"`{k}`" for k in missing_props) or "none", ""]
        count = len(changed) + len(missing_props)
        for cat in CATEGORIES:
            if cat == "custom properties":
                continue
            only_o = sorted(set(o[cat]) - set(c[cat]), key=lambda v: -len(o[cat][v]))
            only_c = sorted(set(c[cat]) - set(o[cat]), key=lambda v: -len(c[cat][v]))
            count += len(only_o) + len(only_c)
            if not only_o and not only_c:
                continue
            diff += [f"### {cat}", "", f"- Only in original ({len(only_o)}): " + ", ".join(f"`{v}` {cite(o[cat][v])}" for v in only_o[:60]),
                     f"- Only in OS ({len(only_c)}): " + ", ".join(f"`{v}` {cite(c[cat][v])}" for v in only_c[:60]), ""]
        totals.append((surface, count))
    diff[3:3] = ["| Surface | Differences |", "|---|---|"] + [f"| {s} | {n} |" for s, n in totals] + [""]
    (out / "design-diff.md").write_text("\n".join(diff) + "\n")
    print("design differences", totals)


if __name__ == "__main__":
    main()
