import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const base=new URL('../../',import.meta.url);
const read=p=>readFileSync(new URL(p,base),'utf8');
const ui=read('frontend/src/lib/admin/AdminCoachDirectoryPanel.svelte');
const api=read('backend/src/LefteriaFc.Api/Audiences/AdminCoachAssignmentEndpoints.cs');
const sql=read('backend/src/LefteriaFc.Infrastructure/Persistence/Migrations/20261108180000_AdminCoachAssignment.cs');
const grants=read('ops/postgres/web-admin-auth-grants.sql');
const boundary=read('ops/postgres/admin-coach-assignment-boundary.sql');
test('coach manager assignment uses owner lock, staff row lock, membership compare and audit',()=>{
  assert.match(sql,/identity\.lock_admin_club_authority\(_digest,_owner\)/);
  assert.match(sql,/v_role NOT IN \('manager','super_admin'\)/);
  assert.match(sql,/FOR UPDATE/);
  assert.match(sql,/v_current<>v_expected/);
  assert.match(sql,/club\.staff_teams/);
  assert.match(sql,/club\.staff_academy_groups/);
  assert.match(sql,/club\.academy_group_coaches/);
  assert.match(sql,/designated_coach_link_conflict/);
  assert.match(sql,/INSERT INTO audit\.security_events/);
  assert.match(grants,/GRANT EXECUTE ON FUNCTION club\.write_admin_coach_assignment/);
  assert.match(boundary,/has_any_column_privilege\(auth_name,c\.oid,'SELECT,INSERT,UPDATE,REFERENCES'\)/);
  assert.doesNotMatch(sql,/contact_provenance|parent_phone|INSERT INTO (chat|messages)\./);
});
test('verified UI and API reject unauthorized, ambiguous or stale writes',()=>{
  assert.match(api,/RequireAuthorization\(WebAdminServices\.Policy\)/);
  assert.match(api,/AdminPermissions\.Has\(session\.User\.Role,capability\)/);
  assert.match(api,/JsonUnmappedMemberHandling\.Disallow/);
  assert.match(api,/keys\.Add\(property\.Name\)/);
  assert.match(ui,/admin-coach-assignment-editor/);
  assert.match(ui,/method:'PUT',credentials:'same-origin',cache:'no-store'/);
  assert.match(ui,/'X-Lefteria-Admin':'1'/);
  assert.match(ui,/expected_group_ids:previous,group_ids:desired/);
  assert.match(ui,/response.status===409/);
  assert.match(ui,/response.status===401/);
  assert.match(ui,/response.status===403/);
  assert.match(ui,/selectedGroups.length>=20/);
  assert.doesNotMatch(ui,/@html|innerHTML|\/api\/admin\/messages/);
});
