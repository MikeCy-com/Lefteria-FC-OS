import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {compile} from 'svelte/compiler';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const form=read('src/routes/academy/registration/+page.svelte');
const proxy=read('src/routes/api/public/academy/registration/+server.ts');
const uploads=read('src/routes/api/public/academy/registration/[registrationId]/documents/+server.ts');
const api=read('../backend/src/LefteriaFc.Api/Marketing/AcademyPublicRegistrationDocumentEndpoints.cs');
const submit=read('../backend/src/LefteriaFc.Api/Marketing/AcademyRegistrationEndpoints.cs');
const migration=read('../backend/src/LefteriaFc.Infrastructure/Persistence/Migrations/20261122190000_AcademyParentDocumentUploadCapability.cs');
const promotion=read('../backend/src/LefteriaFc.Infrastructure/Persistence/Migrations/20261122173000_AcademyRegistrationDocumentPromotion.cs');
const sql=read('../ops/postgres/academy-enrollment-checks.sql');

test('one parent may supply per-child birth certificate or both ID sides across up to five siblings',()=>{
  assert.ok(compile(form,{filename:'academy/registration/+page.svelte',generate:'server'}).js.code.length>100);
  assert.match(form,/let childDocuments=\$state<ChildDocuments\[]>\(\[emptyDocuments\(\)\]\)/);
  assert.match(form,/childDocuments=\[\.\.\.childDocuments,emptyDocuments\(\)\]/);
  assert.match(form,/childDocuments=childDocuments\.filter\(\(_,i\)=>i!==index\+1\)/);
  assert.match(form,/childDocuments\[0\]\.kind/);
  assert.match(form,/childDocuments\[i\+1\]\.kind/);
  assert.match(form,/data-testid="child-document-picker"/);
  assert.match(form,/documentsValid\(index\)/);
  assert.match(form,/\/api\/public\/academy\/registration\/.*\/documents/);
  assert.match(form,/upload_tokens/);
  assert.match(form,/documentUploadStatus==='incomplete'/);
  assert.match(form,/data-testid="retry-child-uploads"/);
  assert.doesNotMatch(form,/localStorage|sessionStorage|window\.open.*upload_tokens/);
});
test('registration commits token reservations atomically with each child and never inserts player directly',()=>{
  assert.match(submit,/submit_public_registration_with_upload/);
  assert.match(submit,/RandomNumberGenerator\.GetBytes\(32\)/);
  assert.match(submit,/SHA256\.HashData\(tokenBytes\)/);
  assert.match(submit,/await transaction\.CommitAsync/);
  assert.match(submit,/upload_tokens=uploadTokens/);
  assert.match(migration,/CREATE TABLE academy_intake\.registration_upload_capabilities/);
  assert.match(migration,/token_digest char\(64\)/);
  assert.match(migration,/CREATE FUNCTION academy_intake\.submit_public_registration_with_upload/);
  assert.match(migration,/REVOKE ALL ON FUNCTION\s+academy_intake\.submit_public_registration_with_upload/);
  assert.doesNotMatch(migration,/GRANT EXECUTE|GRANT (SELECT|INSERT|UPDATE)/);
});
test('file upload grants are child-bound, limited, encrypted and never served to public routes',()=>{
  assert.match(submit,/MapAcademyPublicRegistrationDocuments/);
  assert.match(api,/AcademyRegistration:Enabled/);
  assert.match(api,/AcademyRegistration:FingerprintKey/);
  assert.match(api,/DocumentVault:KeyBase64/);
  assert.match(api,/RecognizeSafeMime\(plaintext\)/);
  assert.match(api,/new AesGcm\(key,16\)/);
  assert.match(api,/store_public_registration_document/);
  assert.match(api,/registrationId.*objectId:D/);
  assert.match(api,/CryptographicOperations\.ZeroMemory\(plaintext\)/);
  assert.match(migration,/c\.registration_id=_registration/);
  assert.match(migration,/c\.token_digest=_token_digest/);
  assert.match(migration,/c\.expires_at>clock_timestamp\(\)/);
  assert.match(migration,/r\.status='pending'/);
  assert.match(migration,/UNIQUE\(registration_id,document_slot\)|registration_document_slot_conflict/);
  assert.match(migration,/REVOKE ALL ON FUNCTION\s+academy_intake\.store_public_registration_document/);
  assert.match(promotion,/INSERT INTO academy_private\.player_documents/);
  assert.match(sql,/Child 1 document token accessed child 2/);
  assert.match(sql,/Private document retry was not idempotent/);
  assert.match(sql,/Family % child documents count wrong/);
});
test('same-origin proxy strips cookies, caps file size and returns only validated statuses',()=>{
  assert.match(proxy,/upload_tokens/);
  assert.match(proxy,/new Set\(result\.upload_tokens\)/);
  assert.match(proxy,/parseAcademyRegistrationReceipts/);
  assert.match(proxy,/Object\.hasOwn/);
  assert.match(uploads,/request\.headers\.get\('origin'\)!==url\.origin/);
  assert.match(uploads,/size>11\*1024\*1024/);
  assert.match(uploads,/credentials:'omit'/);
  assert.match(uploads,/cache:'no-store'/);
  assert.match(uploads,/payload\.status==='quarantined'/);
  assert.doesNotMatch(uploads,/request\.headers\.get\('cookie'\)|request\.headers\.get\('authorization'\)/i);
});
