import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../../'+p,import.meta.url),'utf8');
const db=read('backend/src/LefteriaFc.Infrastructure/Persistence/Migrations/20261110174000_GuardianRecipientConsent.cs');
const roles=read('backend/src/LefteriaFc.Infrastructure/Persistence/Migrations/20261110173000_MultipleGuardianPermissions.cs');
const service=read('backend/src/LefteriaFc.Application/Family/GuardianPermissionService.cs');
const repo=read('backend/src/LefteriaFc.Infrastructure/Family/PostgresGuardianPermissionRepository.cs');
const api=read('backend/src/LefteriaFc.Api/Family/ParentFamilyEndpoints.cs');
const page=read('frontend/src/routes/app/[...path]/+page.svelte');
const mobile=read('frontend/src/lib/mobile/controller.ts');
const ui=read('frontend/src/lib/mobile/components/MobileGuardianConsent.svelte');
const grant=read('ops/postgres/guardian-permission-grants.sql');
const checks=read('ops/postgres/guardian-permission-boundary.sql');
test('recipient inbox is bound to verified current phone and hides child private data',()=>{
  assert.match(db,/recipient_guardian_permissions/);
  assert.match(db,/i.id=_actor AND i.normalized_phone=_phone AND i.is_active/);
  assert.match(db,/i.role=_role AND _role IN \('fan','parent'\)/);
  assert.match(db,/g.target_phone=_phone AND g.status='pending'/);
  assert.match(db,/player.is_active AND NOT player.is_archived AND NOT player.is_transferred/);
  assert.doesNotMatch(db,/jsonb_build_object\([\s\S]{0,240}'player_id'/);
  assert.match(service,/RequireRecipient\(session\)/);
  assert.match(mobile,/validGuardianRecipientInbox/);
});
test('acceptance requires OTP-authorized identity, live canonical parent and active player',()=>{
  assert.match(db,/recipient.id=_actor AND recipient.normalized_phone=_phone/);
  assert.match(db,/recipient.role=_role AND recipient.is_active/);
  assert.match(db,/source.role='parent'/);
  assert.match(db,/link.kind='guardian'/);
  assert.match(db,/binding.kind='guardian'/);
  assert.match(db,/FOR SHARE OF recipient,source,link,binding,player/);
  assert.match(db,/FOR UPDATE/);
  assert.match(db,/status='accepted_pending_access'/);
  assert.match(db,/target_identity_id=_actor,accepted_at=v_now/);
  assert.match(db,/audit.security_events/);
  assert.doesNotMatch(db,/UPDATE identity.mobile_identities|INSERT INTO identity.mobile_record_links|GRANT SELECT ON/);
});
test('recipient can decline but not gain parent data through consent alone',()=>{
  assert.match(db,/decline_recipient_guardian_permission/);
  assert.match(db,/status='declined'/);
  assert.match(db,/status='pending' AND expires_at>v_now/);
  assert.match(db,/Deliberately not 'active'/);
  assert.match(roles,/accepted_pending_access/);
  assert.match(service,/result.Status!="accepted_pending_access"/);
  assert.match(ui,/Δεν ενεργοποιεί ακόμη πρόσβαση σε προσωπικά στοιχεία παιδιών/);
  assert.match(mobile,/Η πρόσβαση γονέα δεν έχει ενεργοποιηθεί ακόμη/);
});
test('backend consent endpoints, session-aware controller, recipient UI and secret-free DTOs connect',()=>{
  assert.match(api,/GetRecipientGuardianInvitations/);
  assert.match(api,/AcceptRecipientGuardianConsent/);
  assert.match(api,/DeclineRecipientGuardianConsent/);
  assert.match(api,/RequireAuthorization\(IdentityServices.Policy\)/);
  assert.match(repo,/identity.accept_recipient_guardian_permission/);
  assert.match(repo,/identity.read_recipient_guardian_permissions/);
  assert.match(repo,/identity.decline_recipient_guardian_permission/);
  assert.match(mobile,/async function loadGuardianRecipientInbox/);
  assert.match(mobile,/async function respondGuardianRecipient/);
  assert.match(page,/MobileGuardianConsent/);
  assert.match(page,/onRespond=\{\(id,accept\) => controller.respondGuardianRecipient/);
  assert.match(grant,/identity.accept_recipient_guardian_permission/);
  assert.match(checks,/guardian_unauthorized_accept_allowed/);
  assert.doesNotMatch(ui,/localStorage|sessionStorage|\{@html/);
});
