test('profile SQL mutations are account-first locked, audited, self-only and password rotation revokes all sessions',()=>{
  assert.match(sql,/LANGUAGE plpgsql VOLATILE SECURITY DEFINER/);
  assert.match(sql,/SET search_path=pg_catalog,pg_temp/);
  assert.match(sql,/WHERE a\.id=v_account FOR UPDATE/);
  assert.match(sql,/s\.revoked_at IS NULL AND s\.expires_at>clock_timestamp\(\) FOR UPDATE/);
  assert.match(sql,/v_hash<>_expected_hash/);
  assert.match(sql,/UPDATE identity\.admin_accounts SET display_name=_name WHERE id=v_account/);
  assert.match(sql,/UPDATE identity\.admin_accounts SET password_hash=_next_hash WHERE id=v_account/);
  assert.match(sql,/UPDATE identity\.admin_sessions/);
  assert.match(sql,/WHERE admin_account_id=v_account AND revoked_at IS NULL/);
  assert.match(sql,/INSERT INTO audit\.security_events/);
  assert.match(sql,/REVOKE ALL ON FUNCTION identity\.write_admin_own_name/);
  assert.match(sql,/DROP FUNCTION identity\.write_admin_own_password/);
  assert.match(grants,/GRANT EXECUTE ON FUNCTION identity\.write_admin_own_name/);
  assert.match(grants,/identity\.write_admin_own_password\(text,text,text\)/);
  assert.match(grants,/FROM PUBLIC, :"app_role"/);
  assert.match(checks,/admin-self-profile-boundary\.sql/);
  assert.match(checks,/Self-profile function grants or SECURITY DEFINER boundary invalid/);
  assert.match(boundary,/Self-name API SQL accepted a non-existent current session/);
  assert.match(boundary,/Self-password API SQL accepted a non-existent current session/);
});
